"""Build a self-contained HTML distribution in singlefile/index.html."""

from __future__ import annotations

import re
import base64
import mimetypes
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "index.html"
OUTPUT = ROOT / "singlefile" / "index.html"
RUNTIME_FILES = (
    "scramjet/scramjet.js",
    "controller/controller.api.js",
    "controller/epoxy.js",
    "controller/controller.inject.js",
    "controller/controller.sw.js",
    "scramjet/scramjet.wasm",
    "client/polymorphic-handshake.js",
)
EMBED_DIRS = (
    "assets",
    "extensions",
    "internals",
    "Mockups",
)


def inline_scripts(html: str) -> str:
    pattern = re.compile(
        r'<script\s+src="([^"]+)"\s*></script>',
        flags=re.IGNORECASE,
    )

    def replace(match: re.Match[str]) -> str:
        asset = match.group(1).lstrip("/")
        path = ROOT / asset
        if not path.is_file():
            raise FileNotFoundError(f"Missing script asset: {path}")
        return f"<script>\n{path.read_text(encoding='utf-8')}\n</script>"

    return pattern.sub(replace, html)


def inline_styles(html: str) -> str:
    pattern = re.compile(r'<link\s+[^>]*?rel=["\']stylesheet["\'][^>]*?href=["\']([^"\']+)["\'][^>]*>', re.I)

    def replace(match: re.Match[str]) -> str:
        asset = match.group(1).lstrip("/")
        path = ROOT / asset
        if not path.is_file():
            raise FileNotFoundError(f"Missing stylesheet asset: {path}")
        return f"<style>\n{path.read_text(encoding='utf-8')}\n</style>"

    return pattern.sub(replace, html)


def data_url(path: Path) -> str:
    mime = mimetypes.guess_type(path.name)[0] or "application/octet-stream"
    encoded = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:{mime};base64,{encoded}"


def embedded_asset_bootstrap() -> str:
    assets: dict[str, str] = {}
    for relative in RUNTIME_FILES:
        path = ROOT / relative
        if path.is_file():
            assets[relative] = data_url(path)
    for directory in EMBED_DIRS:
        base = ROOT / directory
        if not base.is_dir():
            continue
        for path in base.rglob("*"):
            if path.is_file():
                assets[path.relative_to(ROOT).as_posix()] = data_url(path)

    assets_json = __import__("json").dumps(assets)
    return f"""<script>
window.__SU_EMBEDDED_ASSETS__ = {assets_json};
const __suOriginalAppPath = null;
window.__SU_APP_ASSET_URL__ = path => {{
  const clean = String(path).replace(/^\\/+/, '');
  return window.__SU_EMBEDDED_ASSETS__[clean] || null;
}};
const APP_BASE = new URL('./', location.href).pathname;
const appPath = path => window.__SU_APP_ASSET_URL__(path) || `${{APP_BASE}}${{path.replace(/^\\/+/, '')}}`;
</script>"""


def main() -> None:
    html = SOURCE.read_text(encoding="utf-8")
    html = inline_styles(html)
    html = inline_scripts(html)
    html = re.sub(
        r'<link\s+[^>]*?rel=["\']icon["\'][^>]*?href=["\']([^"\']+)["\'][^>]*>',
        lambda match: (
            match.group(0).replace(
                match.group(1),
                data_url(ROOT / match.group(1).lstrip("/")),
            )
            if (ROOT / match.group(1).lstrip("/")).is_file()
            else match.group(0)
        ),
        html,
        flags=re.I,
    )
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    # Replace the source appPath/bootstrap block with the embedded asset map.
    bootstrap = embedded_asset_bootstrap()
    html = re.sub(
        r"<script>\s*const APP_BASE = new URL\('\./', location\.href\)\.pathname;.*?</script>",
        bootstrap,
        html,
        count=1,
        flags=re.S,
    )
    OUTPUT.write_text(
        "<!-- Generated by build_singlefile.py; edit index.html instead. -->\n"
        + html,
        encoding="utf-8",
    )
    print(f"Built {OUTPUT}")


if __name__ == "__main__":
    main()
