"""Build a self-contained HTML distribution in singlefile/index.html."""

from __future__ import annotations

import base64
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "index.html"
OUTPUT = ROOT / "singlefile" / "index.html"


def inline_scripts(html: str) -> str:
    pattern = re.compile(
        r'<script\s+src="([^"]+)"\s*></script>',
        flags=re.IGNORECASE,
    )

    def replace(match: re.Match[str]) -> str:
        asset = match.group(1).lstrip("/")
        path = ROOT / asset
        if not path.is_file():
            raise FileNotFoundError(f"Missing script asset: {path}")
        return f"<script>\n{path.read_text(encoding='utf-8')}\n</script>"

    return pattern.sub(replace, html)


def inline_icons(html: str) -> str:
    pattern = re.compile(r'/assets/shortcuts/icons/([a-z0-9-]+)\.png')

    def replace(match: re.Match[str]) -> str:
        path = ROOT / "assets" / "shortcuts" / "icons" / f"{match.group(1)}.png"
        encoded = base64.b64encode(path.read_bytes()).decode("ascii")
        return f"data:image/png;base64,{encoded}"

    return pattern.sub(replace, html)


def main() -> None:
    html = SOURCE.read_text(encoding="utf-8")
    html = inline_scripts(html)
    html = inline_icons(html)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        "<!-- Generated by build_singlefile.py; edit index.html instead. -->\n"
        + html,
        encoding="utf-8",
    )
    print(f"Built {OUTPUT}")


if __name__ == "__main__":
    main()
