"""Build a self-contained HTML distribution in singlefile/index.html."""

from __future__ import annotations

import re
import shutil
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "index.html"
OUTPUT = ROOT / "singlefile" / "index.html"
RUNTIME_FILES = (
    "controller/controller.inject.js",
    "controller/controller.sw.js",
    "scramjet/scramjet.js",
    "scramjet/scramjet.wasm",
)


def inline_scripts(html: str) -> str:
    pattern = re.compile(
        r'<script\s+src="([^"]+)"\s*></script>',
        flags=re.IGNORECASE,
    )

    def replace(match: re.Match[str]) -> str:
        asset = match.group(1).lstrip("/")
        path = ROOT / asset
        if not path.is_file():
            raise FileNotFoundError(f"Missing script asset: {path}")
        return f"<script>\n{path.read_text(encoding='utf-8')}\n</script>"

    return pattern.sub(replace, html)


def copy_runtime_assets() -> None:
    output_dir = OUTPUT.parent
    for relative in RUNTIME_FILES:
        source = ROOT / relative
        destination = output_dir / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
    icon_source = ROOT / "assets" / "shortcuts" / "icons"
    if icon_source.is_dir():
        shutil.copytree(
            icon_source,
            output_dir / "assets" / "shortcuts" / "icons",
            dirs_exist_ok=True,
        )
    extension_catalog = ROOT / "extensions" / "scripts" / "index.json"
    if extension_catalog.is_file():
        shutil.copytree(
            extension_catalog.parent,
            output_dir / "extensions" / "scripts",
            dirs_exist_ok=True,
        )
    shutil.copy2(ROOT / "sw.js", output_dir / "sw.js")
    shutil.copy2(ROOT / "_headers", output_dir / "_headers")
    games_source = ROOT / "internals" / "games"
    if games_source.is_dir():
        shutil.copytree(
            games_source,
            output_dir / "internals" / "games",
            dirs_exist_ok=True,
        )
    learning_source = ROOT / "Mockups" / "learning.html"
    if not learning_source.is_file():
        raise FileNotFoundError(f"Missing learning mockup: {learning_source}")
    learning_destination = output_dir / "Mockups" / "learning.html"
    learning_destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(learning_source, learning_destination)


def main() -> None:
    html = SOURCE.read_text(encoding="utf-8")
    html = inline_scripts(html)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    copy_runtime_assets()
    OUTPUT.write_text(
        "<!-- Generated by build_singlefile.py; edit index.html instead. -->\n"
        + html,
        encoding="utf-8",
    )
    print(f"Built {OUTPUT}")


if __name__ == "__main__":
    main()
