"""Build a self-contained HTML distribution in singlefile/index.html."""

from __future__ import annotations

import base64
import json
import re
import shutil
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "index.html"
OUTPUT = ROOT / "singlefile" / "index.html"
RUNTIME_FILES = (
    "controller/controller.inject.js",
    "controller/controller.sw.js",
    "scramjet/scramjet.js",
    "scramjet/scramjet.wasm",
)


def inline_scripts(html: str) -> str:
    pattern = re.compile(
        r'<script\s+src="([^"]+)"\s*></script>',
        flags=re.IGNORECASE,
    )

    def replace(match: re.Match[str]) -> str:
        asset = match.group(1).lstrip("/")
        path = ROOT / asset
        if not path.is_file():
            raise FileNotFoundError(f"Missing script asset: {path}")
        return f"<script>\n{path.read_text(encoding='utf-8')}\n</script>"

    return pattern.sub(replace, html)


def inline_icons(html: str) -> str:
    icon_dir = ROOT / "assets" / "shortcuts" / "icons"
    titles = {
        "chatgpt": "ChatGPT",
        "discord": "Discord",
        "google": "Google",
        "youtube": "YouTube",
    }
    icon_data = {}
    for path in sorted(icon_dir.glob("*.png")):
        encoded = base64.b64encode(path.read_bytes()).decode("ascii")
        icon_data[titles.get(path.stem, path.stem.title())] = f"data:image/png;base64,{encoded}"

    html = html.replace(
        'src="${appPath(`assets/shortcuts/icons/${encodeURIComponent(shortcut.title.toLowerCase())}.png`)}"',
        'src="${shortcutIcons[shortcut.title] || ""}"',
    )
    icon_map = json.dumps(icon_data, separators=(",", ":"))
    marker = "  const logDrawer"
    if marker not in html:
        raise ValueError("Could not locate the main application script")
    return html.replace(marker, f"  const shortcutIcons = {icon_map};\n{marker}", 1)


def copy_runtime_assets() -> None:
    output_dir = OUTPUT.parent
    for relative in RUNTIME_FILES:
        source = ROOT / relative
        destination = output_dir / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
    icon_source = ROOT / "assets" / "shortcuts" / "icons"
    if icon_source.is_dir():
        shutil.copytree(
            icon_source,
            output_dir / "assets" / "shortcuts" / "icons",
            dirs_exist_ok=True,
        )
    extension_catalog = ROOT / "extensions" / "scripts" / "index.json"
    if extension_catalog.is_file():
        shutil.copytree(
            extension_catalog.parent,
            output_dir / "extensions" / "scripts",
            dirs_exist_ok=True,
        )
    shutil.copy2(ROOT / "sw.js", output_dir / "sw.js")
    shutil.copy2(ROOT / "_headers", output_dir / "_headers")


def main() -> None:
    html = SOURCE.read_text(encoding="utf-8")
    html = inline_scripts(html)
    html = inline_icons(html)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    copy_runtime_assets()
    OUTPUT.write_text(
        "<!-- Generated by build_singlefile.py; edit index.html instead. -->\n"
        + html,
        encoding="utf-8",
    )
    print(f"Built {OUTPUT}")


if __name__ == "__main__":
    main()
